// 4.102 — 정박지 자리 검수 (사장님: 「눈으로 직접 하나하나 다 확인하라」)
//
// ★ 무슨 일이 있었나
//   관 자료(해양수산부 「전국 마리나 현황」)에는 좌표가 없다. 그래서 이름을 지도에 물어봤는데
//   「수산마리나」 → 강원도 산속, 「오산마리나」 → 경산, 「사동마리나」 → 대구,
//   「진해 명동 마리나」 → 부산 북항 으로 찍혀 있었다. 그 점을 믿고 배를 몰면 산으로 간다.
//
// ★ 이 검사가 지키는 것
//   ① 사람이 눈으로 확인해 적어 둔 자리가 자료에 **그대로** 들어 있다
//   ② 자리를 못 찾은 곳은 **안 실린다** (엉뚱한 점을 찍느니 없는 편이 낫다)
//   ③ 배를 매는 곳이 아닌 것은 **안 실린다**
//   ④ 나라 꾸러미에 남의 나라 자리가 안 섞인다
const fs = require('fs'), path = require('path');
const 뿌리 = path.join(__dirname, '..', '..');
const 손 = require(path.join(뿌리, 'webout/scripts/spot_hand.js'));
const 자료칸 = process.argv[3] || path.join(뿌리, 'rev/out');
const kr = JSON.parse(fs.readFileSync(path.join(자료칸, 'spots-kr.json'), 'utf8'));
const jp = JSON.parse(fs.readFileSync(path.join(자료칸, 'spots-jp.json'), 'utf8'));
// ★ 4.102 — 러시아 꾸러미도 본다. 처음에 한국·일본만 보고 러시아를 빼먹었다 (사장님이 짚으셨다).
//   자료가 없으면(아직 안 나갔으면) 빈 것으로 두고 넘어간다 — 없다고 검사가 죽으면 안 된다.
let ru = { rows: [] };
try{ ru = JSON.parse(fs.readFileSync(path.join(자료칸, 'spots-ru.json'), 'utf8')); }catch(_){}
const app = fs.readFileSync(process.argv[2] || path.join(뿌리, 'work.html'), 'utf8');

let pass = 0, fail = 0;
const T = (n, c) => { if(c){ pass++; console.log('통과: ' + n); } else { fail++; console.log('★ 실패: ' + n); } };
const km = (a, b) => Math.hypot((a.la - b.la) * 111, (a.lo - b.lo) * 111 * Math.cos(a.la * Math.PI / 180));
const 찾 = (rows, n) => rows.find(x => x.n === n);

// ── 앱 안의 관 어항 자료
const seedSrc = app.slice(app.indexOf('const SPOT_SEED = ['), app.indexOf('\n];', app.indexOf('const SPOT_SEED = [')) + 3);
const SEED = eval(seedSrc.slice(seedSrc.indexOf('[')));

// ① 사람이 확인한 자리가 그대로 들어 있다
Object.entries(손.손으로찍은자리).forEach(([n, v]) => {
  const r = 찾(kr.rows, n);
  if(!r) return;                     // 아직 안 실린 것은 ②에서 따로 본다
  T('★★★ 사람이 확인한 자리 그대로 — ' + n, km(r, v) < 0.1);
});

// ② 자리를 못 찾은 곳은 안 실린다
Object.keys(손.자리를못찾은곳).forEach(n => {
  T('★★★ 자리를 못 찾아 안 싣는다 — ' + n, !찾(kr.rows, n));
});

// ③ 배를 매는 곳이 아닌 것은 안 실린다 — 세 꾸러미 **모두**에서
Object.keys(손.계류자리아님).forEach(n => {
  T('배 매는 곳이 아니라 뺐다 — ' + n.slice(0, 22),
    !찾(kr.rows, n) && !찾(jp.rows, n) && !찾(ru.rows, n));
});
// ★★★ 러시아 꾸러미 — 남의 나라가 안 섞이나
if(ru.rows.length){
  T('★★★ 러시아 꾸러미에 중국 방천(防川) 선착장이 없다', !찾(ru.rows, '防川第一码头'));
  T('★★★ 러시아 꾸러미가 모두 러시아 극동 네모 안이다',
    ru.rows.every(x => x.la >= 42 && x.la <= 55 && x.lo >= 130 && x.lo <= 145),
    ru.rows.filter(x => !(x.la >= 42 && x.la <= 55 && x.lo >= 130 && x.lo <= 145)).map(x => x.n));
  T('★★★ 러시아 꾸러미에 해상여객터미널·나루터가 없다',
    !ru.rows.some(x => /Морвокзал|Паромн/i.test(x.n)), ru.rows.map(x => x.n));
  T('러시아 꾸러미에도 왜 뺐는지 적혀 있다', !!ru.배매는곳이아니라뺀것);
}

// ④ 나라 꾸러미에 남의 나라가 안 섞인다
//   대한해협 한가운데(129.2°E)를 넘는 한국 자료는 대마도다 (Takashiki Marina 가 그랬다)
T('★★★ 한국 꾸러미에 일본 자리가 없다',
  !kr.rows.some(x => x.la < 34.6 && x.lo > 129.0));
T('한국 꾸러미가 모두 우리 네모 안이다',
  kr.rows.every(x => x.la >= 33 && x.la <= 39 && x.lo >= 124 && x.lo <= 132));

// ⑤ 사장님이 짚으신 네 곳 — 이름이 가리키는 곳에 있나
const 못박기 = [
  ['진해 명동 마리나', 35.09, 128.72, '창원 진해구 명동 (부산 북항이 아니다)'],
  ['수산마리나',       38.08, 128.68, '양양 수산항 (강원도 산속이 아니다)'],
  ['오산마리나',       36.89, 129.42, '울진 오산항 (경산이 아니다)'],
  ['사동마리나',       36.83, 129.45, '울진 사동항 (대구가 아니다)'],
  ['원형마리나',       34.75, 127.67, '여수 웅천 (여수 시내 산이 아니다)'],
  ['신창마리나',       33.35, 126.17, '제주 한경면 신창항 (제주시 한가운데가 아니다)'],
  ['봉암항 요트계류시설', 34.75, 128.50, '통영 한산면 추봉리 (창원 봉암동이 아니다)']
];
못박기.forEach(([n, la, lo, 왜]) => {
  const r = 찾(kr.rows, n);
  T('★★★ ' + n + ' — ' + 왜, !!r && km(r, { la, lo }) < 3);
});

// ⑤-2 나중에 자리를 찾은 곳 — 표에 제대로 들어갔나 (자료에는 다음 수집 때 들어온다)
[['해운대마리나', 35.1566, 129.1521, '해운대 더베이101 (해운대 좌동 안쪽이 아니다)'],
 ['광안리 해양 레포츠센터', 35.1462, 129.1153, '광안리해수욕장 남쪽 (연제구 안쪽이 아니다)'],
 ['연대항 요트계류시설', 34.7333, 128.3833, '통영 산양읍 연대항 (김해가 아니다)'],
 ['삼락수상레포츠타운', 35.1687, 128.9680, '사상구 삼락동 낙동강변 (부산시 한가운데가 아니다)']
].forEach(([n, la, lo, 왜]) => {
  const v = 손.손으로찍은자리[n];
  T('★★★ ' + n + ' — ' + 왜, !!v && km(v, { la, lo }) < 1, v);
  T('그리고 「못 찾은 곳」 에서 빠졌다 — ' + n, !손.자리를못찾은곳[n]);
});

// ⑤-3 일본 정박지 이름 읽는 법 (사장님: 「일본 항구들 번역 안 된 건 이유가 머지?」)
{
  const 읽 = 손.일본이름읽기 || {};
  T('★★★ 사람이 찾아 적어 둔 일본 이름 읽기가 있다', Object.keys(읽).length >= 20, Object.keys(읽).length);
  T('★★★ 읽기마다 가나와 한글이 함께 있다 (가나는 되짚어 볼 근거다)',
    Object.values(읽).every(v => v && v.가나 && v.한글), Object.entries(읽).filter(([,v]) => !(v && v.가나 && v.한글)));
  T('★★★ 港 은 우리 관례대로 「항」 으로 적는다 (요코하마항·고베항과 같게)',
    읽['稚内港'] && 읽['稚内港'].한글 === '왓카나이항', 읽['稚内港']);
  T('★★★ 漁港 은 「어항」', 읽['福島漁港'] && 읽['福島漁港'].한글 === '후쿠시마어항', 읽['福島漁港']);
  T('★★ 촉음도 제대로 읽는다 (わっかない → 왓카나이)',
    읽['稚内港'] && 읽['稚内港'].가나 === 'わっかないこう');
  // 자료에 실제로 붙었나
  const 붙은 = jp.rows.filter(x => x.nm && x.nm['ko']).length;
  T('★★★ 자료에 읽는 법이 실제로 붙었다', 붙은 >= 20, 붙은 + '곳');
  const 왓 = jp.rows.find(x => x.n === '稚内港');
  T('★★ 稚内港 이 「왓카나이항」 으로 읽힌다', !!왓 && 왓.nm && 왓.nm['ko'] === '왓카나이항', 왓 && 왓.nm);
}

// ⑥ 앱 안의 어항 자료 — 손으로 고친 두 곳
const 소안 = SEED.find(x => x.n === '소안항');
T('★★★ 소안항이 소안도에 있다 (사동항 주소가 그대로 들어가 있었다)',
  !!소안 && km(소안, { la: 34.1518, lo: 126.6366 }) < 3);
T('소안항 주소가 소안면이다', !!소안 && String(소안.t).indexOf('소안면') >= 0);
const 진두 = SEED.find(x => x.n === '진두항');
T('★★★ 진두항이 영흥도에 있다', !!진두 && km(진두, { la: 37.2514, lo: 126.4983 }) < 3);
T('「그 밖」 이라는 지역이 없다', !SEED.some(x => x.r === '그 밖'));

// ⑦ 되짚어 확인 — 남의 도가 나오면 안 쓴다
T('★★★ 되짚어 확인: 경남권에 부산 자리가 오면 버린다', 손.도가맞나('경남권', '부산광역시 중구') === false);
T('되짚어 확인: 경남권에 경남 자리는 받는다', 손.도가맞나('경남권', '경상남도 창원시 진해구') === true);
T('되짚어 확인: 자리 이름을 안 주면 안 막는다', 손.도가맞나('경남권', '') === true);

// ⑧ 수집기가 이 표를 본다 (문 하나)
const col = fs.readFileSync(path.join(뿌리, 'webout/scripts/collect_jp.js'), 'utf8');
T('수집기가 spot_hand 를 본다', /require\(['"]\.\/spot_hand\.js['"]\)/.test(col));
T('수집기가 사람이 확인한 자리를 제일 먼저 쓴다', col.indexOf('손.손으로찍은자리[g.n]') > 0);
T('수집기가 못 찾은 곳을 안 싣는다', col.indexOf('손.자리를못찾은곳[g.n]') > 0);
T('수집기가 되짚어 확인을 한다', col.indexOf('손.도가맞나(g.reg') > 0);

// ⑨ 자료 파일에 까닭이 남는다 (다음 사람이 왜 뺐는지 안다)
T('자료에 「사람이 확인한 자리」 가 적혀 있다', !!kr.사람이확인한자리 && Object.keys(kr.사람이확인한자리).length > 10);
T('자료에 「자리를 못 찾아 안 실은 곳」 이 적혀 있다', !!kr.자리를못찾아안실은곳);
T('자료에 「배 매는 곳이 아니라 뺀 것」 이 적혀 있다', !!jp.배매는곳이아니라뺀것);

console.log('합계: ' + pass + '개 통과 / ' + fail + '개 실패');
process.exit(fail ? 1 : 0);
