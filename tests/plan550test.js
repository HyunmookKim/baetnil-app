T('늦은 기록은 위치·날씨·항적을 안 켠다', pl && !/posHere|wxCapture|trkStart/.test(pl));
console.log('합계: ' + ok + '개 통과 / ' + bad + '개 실패');
process.exit(bad ? 1 : 0);
