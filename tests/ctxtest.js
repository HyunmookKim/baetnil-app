// 낱말이 「어느 자리에서」 쓰이는지 보고, 자리에 안 맞는 번역을 막는다 (4.115)
//
// ★★★ 왜 이 검사가 있나 — 사장님 지적, 2026-09-08
//   「지금 반복해서 찐빠가 나는 이유가 니가 일하는 방식이 틀렸을 수도 있으니
//    또 새로운 방법들을 여러가지 강구해봐라」
//
//   맞는 말씀이었다. 여태 번역을 볼 때 **한국어 낱말만** 보고 있었다.
//   사전은 「한국어 문장 → 세 나라말」 이라, 그 낱말이 화면 어디에 쓰이는지가 없다.
//   그래서 다음이 다 틀렸다 — 하나같이 「자리를 몰라서」 난 흠이다.
//
//     · 「나라」   → 설정의 나라 고르기인데 영어로 **Nara**(일본 도시), 일본어로 奈良
//     · 「열기」   → 물고기(볼락)인데 일본어로 開く(열다)
//     · 「자리」   → 사람 태울 자리인데 일본어로 桁(자릿수)
//     · 「세우기」 → 임명인데 일본어로 停止(정지)
//     · 「내보내기」→ 회원 제명인데 일본어로 書き出し(파일 내보내기)
//     · 「선택」   → 고르기 단추인데 optional(선택 사항)
//     · 「세일」   → 돛 달고 가는 것인데 일본어로 セール(바겐세일)
//
//   낱말만 보면 어느 쪽도 맞다. **자리를 봐야 갈린다.**
//
// ★ 이 검사가 하는 일 두 가지
//   ① 한 낱말이 **두 뜻으로 갈라져 쓰이던 자리**를 못 박는다 (아래 목록).
//      다시 합치면 잡는다.
//   ② 자리를 알면 절대 나올 수 없는 번역을 막는다 (나라=Nara 같은 것).
const fs = require('fs'), path = require('path');
const SRC = process.argv[2] || path.join(__dirname, '..', '..', 'work.html');
const src = fs.readFileSync(SRC, 'utf8');
let ok = 0, bad = 0;
const T = (n, c, w) => { if(c){ ok++; console.log('통과: ' + n); }
  else { bad++; console.log('★ 실패: ' + n + (w !== undefined ? ' — ' + String(w).slice(0, 200) : '')); } };
function dicts(){
  const i = src.indexOf('const I18N = {');
  let d = 0, j = src.indexOf('{', i), k;
  for(k = j; k < src.length; k++){
    if(src[k] === '{') d++;
    else if(src[k] === '}'){ d--; if(d === 0){ k++; break; } }
  }
  const g = {};
  (new Function('g', src.slice(i, k).replace('const I18N =', 'g.I18N =') + ';'))(g);
  return g.I18N;
}
const I = dicts();

