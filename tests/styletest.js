//
//   번역을 여러 뭉치로 나눠 하면 뭉치마다 표기가 갈린다. 그것을 사람이 눈으로
//   맞추면 3천 줄에서 반드시 무너진다. 실제로 4.111 에서 맞춰 놓은 것이
//   4.113 에서 또 갈라져 있었다.
//
// ★ 그래서 **정한 것을 여기 한 곳에 적어 두고, 어기면 파일을 못 내보내게** 한다.
//   아래는 전부 4.115 에 사장님 앱을 실제로 세어 보고 **많은 쪽으로** 정한 것이다.
//   지어낸 규칙이 아니다.
const fs = require('fs'), path = require('path');
const SRC = process.argv[2] || path.join(__dirname, '..', '..', 'work.html');
const src = fs.readFileSync(SRC, 'utf8');
let ok = 0, bad = 0;
const T = (n, c, w) => { if(c){ ok++; console.log('통과: ' + n); }
  else { bad++; console.log('★ 실패: ' + n + (w !== undefined ? '\n   ' + String(w).slice(0, 320) : '')); } };
function dicts(){
  const i = src.indexOf('const I18N = {');
  let d = 0, j = src.indexOf('{', i), k;
  for(k = j; k < src.length; k++){
    if(src[k] === '{') d++;
    else if(src[k] === '}'){ d--; if(d === 0){ k++; break; } }
  }
  const g = {};
  (new Function('g', src.slice(i, k).replace('const I18N =', 'g.I18N =') + ';'))(g);
  return g.I18N;
}
const I = dicts();
const 걸린다 = (L, re, 예외) => Object.keys(I[L])
  .filter(k => re.test(String(I[L][k] || '')) && !(예외 && 예외(k, String(I[L][k]))));
const 재기 = (이름, L, re, 예외, 까닭) => {
  const g = 걸린다(L, re, 예외);
  T(이름 + ' (' + g.length + '곳) — ' + 까닭, g.length === 0,
    g.slice(0, 4).map(k => I[L][k].slice(0, 70)).join(' | '));
};

// ══ 일본어 ══════════════════════════════════════════════════════════
// ・ 가운뎃점은 전각 ・ 다. ASCII · 는 한국어 원문에서 딸려 온 자국이다.
재기('일-①', 'ja', /·/, null, '가운뎃점은 전각 ・ 로 (원문 297 : 0)');
// ・ 괄호는 전각 （） 다. 반각 () 는 로마자 사이에서만 쓰이고 일본어 글에는 안 쓴다.
재기('일-②', 'ja', /[()]/, null, '괄호는 전각 （） 로 (원문 118 : 0)');
// ・ 대괄호는 반각 [] 하나로. 영어·러시아어와 같은 모양이라야 세 화면이 같아 보인다.
재기('일-③', 'ja', /[［］]/, null, '대괄호는 반각 [] 로');
// ・ 켜고 끄기는 オン/オフ 다. 入/切 은 가전제품 말이다.
재기('일-④', 'ja', /入にす|切のま/, null, '켜고 끄기는 オン·オフ 로 (원문 46 : 0)');
// ・ 돛은 セール 다. セイル 은 일본 요트계에서 안 쓴다.
재기('일-⑤', 'ja', /セイル/, null, '돛은 セール 로');
// ・ 장음을 빠뜨리지 않는다 (インペラ → インペラー). 다른 부품은 다 장음이 붙어 있다.
재기('일-⑥', 'ja', /インペラ(?!ー)/, null, '장음을 빠뜨리지 않는다');
// ・ 수납칸은 収納スペース 하나다.
재기('일-⑦', 'ja', /収納区画/, null, '수납칸은 収納スペース 로 (원문 28 : 0)');
// ・ 손가락 — **이름 있는 단추는 押す, 지도·도면 같은 바탕은 タップ.**
//   일본 앱이 실제로 그렇게 쓴다. 여태 둘이 섞여 있었다.
재기('일-⑧', 'ja', /(地図|図面)を押/, null, '지도·도면 바탕은 タップ 로');
// ・ 앱 이름은 옮기지 않는다 (4.114 에서 사장님이 정하셨다)
재기('일-⑨', 'ja', /船仕事/, null, '앱 이름을 옮기지 않는다');

// ══ 영어 ════════════════════════════════════════════════════════════
// ・ 홑따옴표는 곧은 것 하나로. 곱슬표가 섞이면 글꼴에 따라 딴 글자로 보인다.
재기('영-①', 'en', /[’‘]/, null, "홑따옴표는 곧은 ' 로");
// ・ ★★★ 이스케이프가 글자로 새어 나간 것 — 화면에 백슬래시가 그대로 찍힌다
재기('영-②', 'en', /\\u[0-9a-fA-F]{4}/, null, '★ 이스케이프가 글자로 새어 나가지 않는다');
// ・ 줄표는 em — 하나로. ' - ' 하이픈은 뺄셈으로 읽힌다.
재기('영-③', 'en', / - /, null, '줄표는 em — 로 (원문 94 : 0)');
// ・ 말줄임은 … 한 글자로.
재기('영-④', 'en', /\.\.\./, null, '말줄임은 … 로');
// ・ 차림표 길은 › 로. > 는 크다는 뜻으로 읽힌다.
재기('영-⑤', 'en', / > /, null, '차림표 길은 › 로');

// ・ 이름표는 문장식(첫 글자만 대문자)이다. 제목식이 섞이면 화면이 어수선해 보인다.
//   ★ 아래 탭이 「My Boat ↔ Other boats」 로 하나만 제목식이었다.
{
  const 이름표 = ['오늘','내 배','남의 배','커뮤니티','날씨 · 물때','출항 전 점검','달력','뉴스',
                  '적재표','정비','장비','항해일지','서류','글판','정박지','중고 장터','배 둘러보기'];
  const 제목식 = 이름표.filter(k => {
    const v = String(I.en[k] || '');
    if(!v) return false;
    const w = v.replace(/[&·›\-]/g, ' ').split(/\s+/).filter(Boolean);
    // 첫 낱말 말고 대문자로 시작하는 낱말이 있으면 제목식이다 (고유명사는 없다)
    return w.slice(1).some(x => /^[A-Z]/.test(x));
  });
  T('영-⑥ 이름표는 문장식이다 (' + 제목식.length + '곳)', 제목식.length === 0,
    제목식.map(k => k + ' → ' + I.en[k]).join(' | '));
}

// ══ 러시아어 ════════════════════════════════════════════════════════
재기('러-①', 'ru', /\.\.\./, null, '말줄임은 … 로');
재기('러-②', 'ru', / > /, null, '차림표 길은 › 로');
// ・ 「너」 로 말하지 않는다. 앱은 처음부터 끝까지 존대다.
재기('러-③', 'ru', /\b(ты|тебя|тебе|твой|твоя|твои)\b/i, null, '존대(Вы)로만 말한다');
// ・ 배는 судно 로. лодка 는 작은 보트라 요트·어선에 안 맞고, 성(性)이 달라 글이 어긋난다.
{
  // ★ 하나만 빼 둔다 — 「모터보트」 는 러시아어로 «моторная лодка» 가 맞는 말이다.
  //   배 종류 이름이라 судно 로 바꾸면 오히려 틀린다.
  const g = 걸린다('ru', /[Лл]одк/, (k) => k === '모터보트·요트 (일반)');
  T('러-④ 배는 судно 로 (' + g.length + '곳)', g.length === 0,
    g.slice(0, 6).map(k => I.ru[k].slice(0, 60)).join(' | '));
}

// ══ 세 말 모두 ══════════════════════════════════════════════════════
// ・ 한국어가 남아 있으면 그 화면만 한글로 나간다 (앱 이름은 뺀다)
['en','ru','ja'].forEach(L => 재기('모두-' + L, L, /[가-힣]/, null, '한국어가 남아 있지 않다'));


// ══ 사전 **바깥**의 한국어 글자도 사전 열쇠와 똑같아야 한다 ═══════════
// ★ 4.115 에서 실제로 났던 일 — 표기를 고르게 맞추다가 사전 바깥의 자료 한 줄까지
//   건드렸다. 「히야마·쓰가루 앞바다」 의 가운뎃점이 ・ 로 바뀌면서 사전 열쇠(·)와
//   글자가 달라졌고, 그 해역만 세 나라말에서 한국어로 나갈 뻔했다.
//   화면은 멀쩡해 보이는데 그 한 줄만 안 옮겨진다 — 사람이 알아채기 제일 어려운 흠이다.
{
  // 코드 안에서 '한국어' 로 적혀 있고 t() 를 거치는 자료 — 일본 해역 이름 표
  const m = src.match(/const JP_SEA_KO\s*=\s*\{[\s\S]*?\n\};/)
         || src.match(/'[^']*沖'\s*:\s*'[^']*',/g) ? src : '';
  const 짝 = [...src.matchAll(/'([^'\n]*[一-鿿][^'\n]*)'\s*:\s*'([^'\n]*[가-힣][^'\n]*)'/g)]
    .map(x => x[2]);
  const 없는것 = [...new Set(짝)].filter(k => /[가-힣]/.test(k) && I.en[k] === undefined
                                            && /[·・]/.test(k));
  T('밖-① ★★★ 사전 바깥의 한국어 이름이 사전에 다 있다 (' + 없는것.length + '곳)',
    없는것.length === 0, 없는것.slice(0, 5).join(' | '));
  // ★ 가운뎃점은 한국어 글에서 ASCII · 하나로 — 사전 열쇠가 그 글자를 쓰기 때문이다
  const 전각섞임 = [...new Set(짝)].filter(k => /・/.test(k));
  T('밖-② ★★★ 사전 바깥의 한국어 이름에 전각 ・ 가 섞이지 않았다 (' + 전각섞임.length + '곳)',
    전각섞임.length === 0, 전각섞임.slice(0, 5).join(' | '));
}

console.log('\n합계: ' + ok + '개 통과 / ' + bad + '개 실패');
