// 화면 말은 **언제나 존댓말**이어야 한다
//
// ★ 사장님 지적 (2026-09-16): 「항해일지 삭제하는데 반말로 안내하더라」
//   실제로 「"…" 휴지통으로 옮길까? (휴지통에서 복원 가능)」 이었다.
//   같은 모양이 네 군데 더 있었다 — 완료 처리할까? · 기준값을 삭제할까? · 항목을 휴지통으로 옮길까?
//   한 곳만 고치면 나머지가 남는다. 그래서 **화면에 뜨는 말 전부**를 훑고 여기서 못 박는다.
//
// ★ 어디를 보나 — 사전(I18N)의 **한국어 열쇠**가 곧 화면에 뜨는 말이다.
//   주석·변수 이름은 안 본다 (그건 사람이 읽는 글이 아니다).
//
// ★ 무엇을 잡나 — **문장이 끝나는 자리**의 반말만 잡는다.
//   「꺼져 있어 안 올라갑니다」 의 '있어' 는 이어 주는 말이라 반말이 아니다.
const fs = require('fs');
const src = fs.readFileSync(process.argv[2] || 'work.html', 'utf8');
const L = src.split('\n');
const at = re => L.findIndex(l => re.test(l)) + 1;
const i = at(/^  en\s*:\s*\{/), j = at(/^  ru\s*:\s*\{/);
const keys = [];
for(const line of L.slice(i - 1, j))
  for(const m of line.matchAll(/'((?:[^'\\]|\\.)*)'\s*:\s*'/g)) keys.push(m[1]);

let ok = 0, bad = 0;
const T = (n, c, x) => { if(c){ ok++; } else { bad++; console.log('★ 실패: ' + n + (x===undefined?'':' — ' + x)); } };
T('화면 말을 읽었다', keys.length > 1000, keys.length + '개');

// 문장이 끝나는 자리 = ? ! . 줄바꿈 또는 글 끝
const 끝 = '(?=\\s*(?:\\\\n|$))';
const 규칙 = [
  // 「~할까?」 — 존댓말은 「~할까요?」 다. 「~습니까?」 는 존댓말이라 뺀다.
  { rx: new RegExp('(?<!니)(?<!ㅂ)까\\?' + 끝),          왜: '~까? (→ ~까요?)' },
  { rx: new RegExp('[가-힣](니|냐)\\?' + 끝),            왜: '~니?/~냐?' },
  { rx: new RegExp('(하자|가자|보자|해라|하라|봐라)' + 끝), 왜: '반말 청유·명령' },
  { rx: new RegExp('(했어|있어|없어|이야|거야|을걸|ㄹ걸)' + 끝), 왜: '반말 평서' },
  // ★ 「해」·「와」 로 끝나는 낱말이 너무 많다(항해 · 야간 항해 · 오가와).
  //   그래서 반말로만 쓰이는 셋만 본다.
  { rx: new RegExp('(줘|봐|돼)' + 끝),                     왜: '반말 종결' },
];
// ★ 반말이 아닌데 모양만 걸리는 것 — 까닭을 적고 뺀다
const 봐줌 = [
  /습니까\?/, /ㅂ니까\?/, /십니까\?/, /입니까\?/, /겠습니까\?/,   // 존댓말 물음
  /^[가-힣]{1,6}$/,                                              // 낱말 하나짜리 이름표 (관심 분야 · 텐야)
];
const 걸린것 = [];
keys.forEach(k => {
  if(봐줌.some(r => r.test(k))) return;
  for(const part of k.split('\\n')){
    const p = part.trim();
    if(!p) continue;
    if(봐줌.some(r => r.test(p))) continue;
    for(const g of 규칙){
      if(g.rx.test(p)){ 걸린것.push({ 왜:g.왜, 말:k.slice(0,70) }); return; }
    }
  }
});
T('★★★ 반말로 말하는 자리가 없다', 걸린것.length === 0,
  걸린것.length ? '\n' + 걸린것.map(x => '   [' + x.왜 + '] ' + x.말).join('\n') : '');

// ── 사장님이 실제로 보신 자리 — 이름을 대고 못 박는다
const 못박기 = [
  ['항해일지·정비 기록을 휴지통으로 옮길 때', '"{name}" 휴지통으로 옮길까요?'],
  ['수납칸을 휴지통으로 옮길 때',             '"{name}" 항목을 휴지통으로 옮길까요?'],
  ['정기점검을 완료 처리할 때',               '"{name}" — 오늘({d}) 완료 처리할까요?'],
  ['조위 기준값을 지울 때',                   '"{name}" 기준값을 삭제할까요?'],
];
못박기.forEach(([어디, 말]) => T('★ ' + 어디 + ' 존댓말이다', src.indexOf("'" + 말) >= 0, 말));
// 옛 반말이 하나도 안 남았다
["휴지통으로 옮길까?", "완료 처리할까?", "삭제할까?"].forEach(x =>
  T('★ 옛 반말이 안 남아 있다 — ' + x, src.indexOf(x) < 0));
// 「복원 가능」 같은 한자어 축약도 안 쓴다 (앱은 「되돌릴 수 있습니다」 로 말한다)
T('★ 「복원 가능」 을 안 쓴다', src.indexOf('복원 가능') < 0);

console.log(`\n${ok}/${ok+bad} 통과`);
process.exit(bad ? 1 : 0);
