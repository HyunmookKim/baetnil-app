function grabF(n){
  let i = src.indexOf('function ' + n + '(');
  if(i < 0){ i = src.indexOf('async function ' + n + '('); if(i < 0) return ''; }
  let d = 0, j = src.indexOf('{', i);
  for(; j < src.length; j++){ if(src[j] === '{') d++; else if(src[j] === '}'){ d--; if(!d){ j++; break; } } }
  return src.slice(i, j);
}
function grabC(n){
  let k = src.indexOf('const ' + n + ' ');
  if(k < 0) k = src.indexOf('const ' + n + '=');
  if(k < 0) return '';
  let j = k, d = 0, st = false;
  for(; j < src.length; j++){
    const c = src[j];
    if(c === '[' || c === '{'){ d++; st = true; }
    else if(c === ']' || c === '}'){ d--; }
    else if(c === ';' && d === 0 && st){ j++; break; }
  }
  return src.slice(k, j);
}

