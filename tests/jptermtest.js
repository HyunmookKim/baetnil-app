// 일본어 뱃말이 그 바닥에서 쓰는 말인가 (4.106)
//
// ★ 왜 이 검사가 있나
//   사장님이 일본을 주무대로 보신다. 그런데 앱의 일본어에 세 군데가 어긋나 있었다.
//   일본 리뷰에는 「日本語じゃないので★１」 만 적고 별 하나를 주는 사람이 실제로 있다.
//   기능을 안 보고 준다. 그래서 낱말 하나가 앱 전체의 값을 깎는다.
//
//   ① 出港前点検 → 発航前検査
//      일본은 「배 띄우기 전 점검」이 **법정 의무**다. 小型船舶操縦者法 의 遵守事項 이고,
//      국토교통성이 「発航前検査」 라고 쓴다. 平成28년(2016) 7월 1일부터 어기면 행정처분이다.
//      (mlit.go.jp/maritime/maritime_fr10_000010.html — 「発航前の検査義務違反は行政処分の対象」)
//      「出港前点検」 이라고 쓰면 그냥 「나가기 전에 살펴보기」 로 읽혀서,
//      일본 사람이 「아, 그 법으로 하게 되어 있는 검사」 라고 알아보지 못한다.
//      국토교통성이 배포하는 것도 「チェックリスト」 라, 「発航前検査チェックリスト」 가 그 이름이다.
//
//   ② 停泊地 → 係留地
//      앱 전체가 係留地 인데 딱 한 군데만 停泊地 였다. 그 말은 일본 뱃일에서 쓰는 근거를 못 찾았다.
//
//   ③ 出航 → 出港
//      배는 出港 / 入港 이 한 짝이다. 出航 은 비행기에도 쓰는 말이라 짝이 어긋난다.
//      앱의 나머지 서른여섯 자리가 出港 인데 한 군데만 出航 이었다.
const fs = require('fs'), path = require('path');
const SRC = process.argv[2] || path.join(__dirname, '..', '..', 'work.html');
const src = fs.readFileSync(SRC, 'utf8');
let ok = 0, bad = 0;
const T = (n, c, w) => { if(c){ ok++; console.log('통과: ' + n); }
  else { bad++; console.log('★ 실패: ' + n + (w !== undefined ? ' — ' + String(w).slice(0, 200) : '')); } };

// 일본어 사전만 떼어 본다 — 한국어 원문에는 한자가 안 들어 있다
const JA = (src.match(/\n  ja: \{[\s\S]*?\n  \},/) || [''])[0];
T('일본어 사전을 읽었다', JA.length > 1000, JA.length);

// ── ① 발항전검사
T('①-1 ★ 일본 법령어 「発航前検査」를 쓴다', JA.indexOf('発航前検査') >= 0);
T('①-2 ★ 「出港前点検」이 남아 있지 않다', src.indexOf('出港前点検') < 0,
  (src.match(/[^\n]{0,60}出港前点検[^\n]{0,40}/) || [''])[0]);
T('①-3 ★ 점검표 이름도 국토교통성 것과 같다 (発航前検査チェックリスト)',
  JA.indexOf('発航前検査チェックリスト') >= 0 && src.indexOf('出港前チェックリスト') < 0);
T('①-4 「출항 전 점검」의 일본어가 법령어다',
  /'출항 전 점검':'発航前検査'/.test(JA), (JA.match(/'출항 전 점검':'[^']*'/) || [''])[0]);
// ★ 出港前 자체는 그대로 둔다 — 「出港前・入港後」 처럼 때를 가리키는 자리와,
//   「出港前の届出」(출입항 신고) 는 법정 검사와 다른 것이다.
T('①-5 때를 가리키는 「出港前」은 그대로 남아 있다 (다 갈아엎지 않았다)',
  JA.indexOf('出港前・入港後') >= 0 || JA.indexOf('出港前に') >= 0);

// ── ② 계류지
T('②-1 ★ 「停泊地」가 남아 있지 않다', src.indexOf('停泊地') < 0,
  (src.match(/[^\n]{0,60}停泊地[^\n]{0,40}/) || [''])[0]);
T('②-2 정박지는 한 낱말로 통일돼 있다 (係留地)', (JA.match(/係留地/g) || []).length >= 10,
  (JA.match(/係留地/g) || []).length);

// ── ③ 출항
T('③-1 ★ 「出航」이 남아 있지 않다 (배는 出港/入港 이 한 짝이다)', src.indexOf('出航') < 0,
  (src.match(/[^\n]{0,60}出航[^\n]{0,40}/) || [''])[0]);
T('③-2 出港 이 짝으로 쓰인다', (JA.match(/出港/g) || []).length >= 20 && JA.indexOf('入港') >= 0,
  (JA.match(/出港/g) || []).length);

// ── 그 밖에 이미 맞게 되어 있는 것 — 되돌아가지 않게 못 박는다
// ★ 물때는 「潮汐」로 쓴다 — 일본 기상청이 쓰는 말이고, 뱃일이 그 기상청 자료를 그대로 받는다.
//   낚시 앱들은 「潮見表」(물때표)를 쓰는데, 그건 표 이름이지 현상 이름이 아니다.
//   스토어 소개 문구에는 「潮見表」를 같이 적어 두는 편이 사람들이 찾기에 낫다 (별도 판단).
[['潮汐',   '물때는 일본 기상청이 쓰는 말로 쓴다'],
 ['入港',   '入港 이 出港 과 짝을 이룬다'],
 ['航海日誌', '항해일지는 航海日誌 다']].forEach(([w, why]) =>
  T('④ 「' + w + '」 — ' + why, JA.indexOf(w) >= 0));

// ★ 일본에서 航海日誌 는 레저 배에 법적 의무가 **아니다**
//   (船員法施行規則 제1조의2 가 「スポーツ又はレクリエーションの用に供するヨット又はモーターボート」 를 뺀다).
//   그러니 일본어 어디에도 「법으로 정해져 있다」 는 말을 붙이면 안 된다 — 거짓말이 된다.
{
  const 위험 = [];
  const re = /'([^']*)':'([^']*)'/g;
  let m;
  while((m = re.exec(JA))){
    const ja = m[2];
    if(/航海日誌/.test(ja) && /(義務|法律で|法令で|法定|必須です)/.test(ja)) 위험.push(ja.slice(0, 60));
  }
  T('⑤ ★ 航海日誌를 「법으로 정해져 있다」고 말하지 않는다 (레저 배는 적용 제외다)',
    위험.length === 0, 위험);
}

// ── ⑥ 물때 이름
// ★★ 「무시」의 일본어가 「無視」였다. 일본말로 「無視」는 **「못 본 척한다」**는 뜻이다.
//   한자만 같고 뜻이 정반대다. 물때 자리에 「無視」가 뜨면 일본 사람은 앱이 고장 난 줄 안다.
//
//   무시는 서해식에서 **조금 바로 다음 날**이다 (…13물 · 조금 · 무시 · 1물…).
//
// ★★ 4.106 에서는 그 자리가 일본의 長潮 와 같다고 보아 「長潮」 로 옮겼다.
//   4.110 에서 **그 판단을 뒤집는다.** 일본식 潮名(大潮·中潮·小潮·長潮·若潮)을 통째로
//   넣었기 때문이다. 이제 화면에 진짜 長潮 가 따로 나온다.
//   서해식을 골라 놓고도 「長潮」 가 보이면, 일본 사람은 그것을 일본식 長潮 로 읽는다.
//   두 자리가 늘 같지도 않다 — 서해식은 열다섯 칸을 우리 식으로 세고,
//   일본식은 朔望 을 가운데 둔 제 표로 센다.
//   ★ 그래서 한국 물때 이름은 **옮기지 않고 소리대로 적는다** (무시 → ムシ, 7물 → 7ムル).
//     일본에 없는 말을 일본 낱말로 바꾸면, 그 낱말이 이미 가진 뜻으로 읽힌다.
T('⑥-1 ★ 「무시」가 「無視」(못 본 척한다)로 나가지 않는다',
  !/'무시':'無視'/.test(JA), (JA.match(/'무시':'[^']*'/) || [''])[0]);
T('⑥-2 ★★ 무시는 소리대로 ムシ 다 (일본 낱말로 옮기지 않는다 — 4.110 에서 뒤집었다)',
  /'무시':'ムシ'/.test(JA), (JA.match(/'무시':'[^']*'/) || [''])[0]);
T('⑥-3 사리는 大潮다', /'사리':'大潮'/.test(JA));
T('⑥-4 조금은 小潮다', /'조금':'小潮'/.test(JA));

console.log('\n합계: ' + ok + '개 통과 / ' + bad + '개 실패');
process.exit(bad ? 1 : 0);
