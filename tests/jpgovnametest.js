//   그러니 그 딴이름 안에만 있는 낱말은 세지 않는다 — 세면 검사가 거짓말을 한다.
//   (「牛窓かぜまち桟橋 (関町浮桟橋) (牛窓港)」 의 浮桟橋 가 그 경우다)
const 읽는부분 = 이름 => {
  const 묶음 = 이름.match(/\(([^()]*)\)/g) || [];
  const 본체 = 이름.replace(/\([^()]*\)/g, ' ');
  const 끝 = 묶음.length ? 묶음[묶음.length - 1] : '';   // 마지막 괄호 = 항 이름
  return 본체 + ' ' + 끝;
};
뜻으로.forEach(([원, 우리말]) => {
  const 걸리는것 = Object.keys(표).filter(k => 읽는부분(k).indexOf(원) >= 0);
  const 안옮긴것 = 걸리는것.filter(k => 표[k].한글.indexOf(우리말) < 0);
  T('★★ ' + 원 + ' 은 「' + 우리말 + '」 로 옮긴다 (' + 걸리는것.length + '곳)',
    걸리는것.length > 0 && 안옮긴것.length === 0, 안옮긴것.join(' · '));
});
